DROP TABLE TEMP_SUB_GROSS_ADD IF EXISTS;

CREATE TEMP TABLE TEMP_SUB_GROSS_ADD AS
(
SELECT 
  TO_CHAR(TO_DATE(CAST(TM_KEY_DAY AS VARCHAR(10)), 'YYYYMMDD'), 'YYYYMM')::INT AS MNTH_ID
, TO_DATE(CAST(TM_KEY_DAY AS VARCHAR(10)), 'YYYYMMDD') AS DAY_ID
, CAST(A.PROD_KEY AS INTEGER) AS PROD_KEY
, MSISDN
 
, CASE 
    WHEN ACTIVITY_GROUP = 'NEW'     THEN 'New'
	WHEN ACTIVITY_GROUP = 'MIGRATE' THEN 'Pre2Post'
	WHEN ACTIVITY_GROUP LIKE 'MNP%' THEN 'MNP'
	ELSE 'New'
  END AS SWON_TYPE
, CASE
    WHEN GP_SKU = 'Device Bundling' THEN 'With Device'
    WHEN GP_SKU = 'Open Market'     THEN 'With Device'
    WHEN GP_SKU = 'Migrate' 		THEN 'Pre2Post'
    ELSE 'Sim Only'
  END AS SWON_FLAG
, CASE
    WHEN GP_SKU = 'Convergence' then 'Convergence'
    WHEN UPPER(GP_SKU) LIKE '%DEVICE%' THEN 'With Device'
    WHEN UPPER(GP_SEGMENT) LIKE '%DEVICE%' THEN 'With Device'
	WHEN UPPER(GP_SKU) LIKE '%OPEN MARKET%' THEN 'With Device'
    ELSE 'Sim Only'
  END AS GA_TYPE
, CASE WHEN T_GRP_SP_CH = 'Branded Retail' 
  		AND TDS_SPECIAL_CHANNEL LIKE '%DEALER_B%' THEN 'DEALER_B'
  	WHEN T_GRP_SP_CH = 'Branded Retail' 
  		AND TDS_SPECIAL_CHANNEL LIKE '%DEALER_A%' THEN 'DEALER_A'
  	WHEN T_GRP_SP_CH = 'Branded Retail' 
  		 AND (TDS_SPECIAL_CHANNEL NOT LIKE '%DEALER_B%' OR TDS_SPECIAL_CHANNEL NOT LIKE '%DEALER_A%') THEN 'Other Shop'
    WHEN T_GRP_SP_CH = 'B2B '           THEN 'B2B'
    WHEN T_GRP_SP_CH = 'B2B'            THEN 'B2B'
    WHEN T_GRP_SP_CH = 'Unidentified'   THEN 'Others'
    WHEN T_GRP_SP_CH = 'i) SME'         THEN 'B2B'
    WHEN T_GRP_SP_CH = 'j) Corp'        THEN 'B2B'
    WHEN T_GRP_SP_CH = 'k) Corp M2M'    THEN 'B2B'
    WHEN T_GRP_SP_CH = 'l) Call center' THEN 'Contact Center'
    WHEN T_GRP_SP_CH = 'c) COCO'        THEN 'Other Shop'
    WHEN T_GRP_SP_CH = 'a) FOFO'        THEN 'Other Shop'
    WHEN T_GRP_SP_CH = 'b) Brand B Hall'   THEN 'Other Shop'
    WHEN T_GRP_SP_CH = 'g) Key Account' THEN 'Key Account'
    WHEN T_GRP_SP_CH = 'm) Digital'     THEN 'Own Digital'
    WHEN T_GRP_SP_CH = 'o) Others'      THEN 'Others'
    WHEN T_GRP_SP_CH = 'Other'          THEN 'Others'
    WHEN TDS_CHANNEL = 'Postpaid VAN'   THEN 'Direct Sales'
    WHEN TDS_CHANNEL = 'Blue Shop'      THEN 'Retail Sales'
    WHEN TDS_CHANNEL = 'Modern Trade'   THEN 'Modern Trade'
    WHEN TDS_CHANNEL = 'Other'          THEN 'Others'
    ELSE COALESCE(T_GRP_SP_CH, 'Others')
  END AS GA_CHANNEL
, OUTLET_CODE AS RTR_CD
, OUTLET_NAME AS RTR_NM
, ACTIVATION_VALUE AS INFLOW_AMNT
, FIRST_ACTV_PP_CODE
, FIRST_ACTV_PP_DESC
, PP_TYPE
, SNAP_NET_RC_EXC_ADVP
, PC_EMP_CODE
, ROW_NUMBER() OVER
                  (PARTITION BY MNTH_ID, MSISDN
                   ORDER BY DAY_ID DESC) AS RN
