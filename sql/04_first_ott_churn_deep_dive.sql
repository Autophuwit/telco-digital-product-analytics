                       / TOPPING_BEFORE_REV
                     ) > 0.50
                 AND ( (TOPPING_AFTER_REV - TOPPING_BEFORE_REV)
                       / TOPPING_BEFORE_REV
                     ) <= 1.00
                  THEN '03|50–100%'

                WHEN ( (TOPPING_AFTER_REV - TOPPING_BEFORE_REV)
                       / TOPPING_BEFORE_REV
                     ) > 1.00
                 AND ( (TOPPING_AFTER_REV - TOPPING_BEFORE_REV)
                       / TOPPING_BEFORE_REV
                     ) <= 2.00
                  THEN '04|100–200%'

