-- FIND THE BEFORE AND AFTER REVENUE FOR TOPPING
DROP TABLE IF EXISTS TEMP_SUB_TOPPING_FIRST_OTT;

CREATE LOCAL TEMP TABLE TEMP_SUB_TOPPING_FIRST_OTT ON COMMIT PRESERVE ROWS AS
(
    WITH BASE AS
    (
        SELECT
              B.FIRST_MNTH_ID
            , B.SUBR_ID
            -- month keys computed once per subscriber, so the joins below compare plain INT keys
            -- (no TO_DATE on the revenue table's MNTH_ID -> no per-row conversion, join can use the segmentation)
            , CAST(TO_CHAR(ADD_MONTHS(TO_DATE(CAST(B.FIRST_MNTH_ID AS VARCHAR(6)) || '01', 'YYYYMMDD'), -1), 'YYYYMM') AS INT)
              AS PREV_MNTH_ID
            , CAST(TO_CHAR(ADD_MONTHS(TO_DATE(CAST(B.FIRST_MNTH_ID AS VARCHAR(6)) || '01', 'YYYYMMDD'),  1), 'YYYYMM') AS INT)
              AS NEXT_MNTH_ID
        FROM SANDBOX.AUTO_LIFESTYLE_SUB_AGG_FIRST_OTT B
    )
    SELECT
          B.FIRST_MNTH_ID AS MNTH_ID
        , B.SUBR_ID       AS PROD_KEY

        /* CURRENT MONTH (FIRST_MNTH_ID) */
        , R0.REVN_AMNT    AS REVN_AMNT

        /* BEFORE: FIRST_MNTH_ID - 1 MONTH */
        , CASE
              /* 3) if BOTH M-1 and M+1 have no value → force NULL */
              WHEN R_PRE.REVN_AMNT  IS NULL
               AND R_POST.REVN_AMNT IS NULL THEN NULL

              /* 1) normal: if M-1 exists, use M-1 */
              WHEN R_PRE.REVN_AMNT IS NOT NULL THEN R_PRE.REVN_AMNT

              /* 1) fallback: M-1 missing but M exists → use M */
              WHEN R_PRE.REVN_AMNT IS NULL
               AND R0.REVN_AMNT   IS NOT NULL THEN R0.REVN_AMNT

              ELSE NULL
          END AS TOPPING_BEFORE_REV

        /* AFTER: FIRST_MNTH_ID + 1 MONTH */
        , CASE
              /* 3) if BOTH M-1 and M+1 have no value → force NULL */
              WHEN R_PRE.REVN_AMNT  IS NULL
               AND R_POST.REVN_AMNT IS NULL THEN NULL

              /* 2) M+1 exists */
              WHEN R_POST.REVN_AMNT IS NOT NULL THEN
                   CASE
                       /* if M exists AND M+1 < M → use M */
                       WHEN R0.REVN_AMNT IS NOT NULL
                        AND R_POST.REVN_AMNT < R0.REVN_AMNT
                         THEN R0.REVN_AMNT
                       /* otherwise use M+1 */
                       ELSE R_POST.REVN_AMNT
                   END

              /* 2) fallback: M+1 missing but M exists → use M */
              WHEN R_POST.REVN_AMNT IS NULL
               AND R0.REVN_AMNT    IS NOT NULL THEN R0.REVN_AMNT

              ELSE NULL
          END AS TOPPING_AFTER_REV

    FROM BASE B

    /* CURRENT */
    LEFT JOIN TEMP_INVC_REVN_SUBR_MNTH R0
        ON R0.PROD_KEY = B.SUBR_ID
       AND R0.MNTH_ID     = B.FIRST_MNTH_ID

    /* BEFORE: FIRST_MNTH_ID - 1 MONTH */
    LEFT JOIN TEMP_INVC_REVN_SUBR_MNTH R_PRE
        ON R_PRE.PROD_KEY = B.SUBR_ID
       AND R_PRE.MNTH_ID  = B.PREV_MNTH_ID

    /* AFTER: FIRST_MNTH_ID + 1 MONTH */
    LEFT JOIN TEMP_INVC_REVN_SUBR_MNTH R_POST
        ON R_POST.PROD_KEY = B.SUBR_ID
       AND R_POST.MNTH_ID = B.NEXT_MNTH_ID
)
SEGMENTED BY HASH(MNTH_ID, PROD_KEY) ALL NODES
;

