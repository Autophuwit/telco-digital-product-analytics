	AND MEASURE_TYPE = 'ACTUAL'
	AND ACCOUNT_TYPE_GROUP <> 'SGMT' /* INDIVIDUAL */
	AND COMPANY = 'BRAND_A'
	AND TO_CHAR(TO_DATE(CAST(TM_KEY_DAY AS VARCHAR(10)), 'YYYYMMDD'), 'YYYYMM')::INT BETWEEN R.START_MNTH_ID AND R.END_MNTH_ID
