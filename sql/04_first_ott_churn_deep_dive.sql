-- GROSS ADD BEFORE REVENUE FROM NZ_MART_LEGACY
DROP TABLE TEMP_SUB_GROSS_ADD_PREPAID_REVENUE IF EXISTS;

CREATE TEMP TABLE TEMP_SUB_GROSS_ADD_PREPAID_REVENUE AS
(
SELECT
      TO_CHAR(TO_DATE(CAST(CALL_ST_TM_KEY_DAY AS VARCHAR(10)), 'YYYYMMDD'), 'YYYYMM')::INT AS MNTH_ID
    , A.MSISDN
    , SUM(
          NVL(CAST(A.TOT_MAIN_AMT       AS NUMERIC(12,2)), 0) / 1.07
        + NVL(CAST(A.TOT_CASHBACK_AMT   AS NUMERIC(12,2)), 0)
        + CASE
              WHEN A.REV_CHNL IS NOT NULL
                   THEN NVL(CAST(A.TOT_SRVC_RVN_AMT  AS NUMERIC(12,2)), 0) / 1.07
                   ELSE NVL(CAST(A.TOT_TPPNG_CASH_AMT AS NUMERIC(12,2)), 0) / 1.07
          END
      ) AS REVN_AMNT
FROM NZ_MART_LEGACY.ADMIN.AGG_PREP_REV_SUBS_DAY A
INNER JOIN TEMP_SUB_MSSID_FIRST_OTT B
    ON A.MSISDN = B.REF_RESRE_NBR
CROSS JOIN TEMP_RUN_DATE R
WHERE A.RVN_IND = 1
  AND NVL(A.TEST_IND, 0) <> 1
  AND MNTH_ID BETWEEN R.START_MNTH_ID AND R.END_MNTH_ID
GROUP BY
      TO_CHAR(TO_DATE(CAST(CALL_ST_TM_KEY_DAY AS VARCHAR(10)), 'YYYYMMDD'), 'YYYYMM')::INT
    , A.MSISDN
)
DISTRIBUTE ON (MNTH_ID, MSISDN)
;

