DROP TABLE IF EXISTS TEMP_SUB_GROSS_ADD_PREPAID_REVENUE;

CREATE LOCAL TEMP TABLE TEMP_SUB_GROSS_ADD_PREPAID_REVENUE ON COMMIT PRESERVE ROWS AS
(
    SELECT
          B.FIRST_MNTH_ID
        , B.MSISDN
        , AVG(R.REVN_AMNT) AS PREPAID_REVN_AMNT
    FROM SANDBOX.AUTO_LIFESTYLE_SUB_AGG_FIRST_OTT B
    LEFT JOIN SANDBOX.AUTO_SUB_GROSS_ADD_PREPAID_REVENUE R
      ON R.MSISDN = B.MSISDN
     AND R.MNTH_ID BETWEEN
            CAST(
                TO_CHAR(
                    ADD_MONTHS(
                        TO_DATE(CAST(B.FIRST_MNTH_ID AS VARCHAR(6)) || '01', 'YYYYMMDD'),
                        -3
                    ),
                    'YYYYMM'
                ) AS INTEGER
            )
        AND CAST(
                TO_CHAR(
                    ADD_MONTHS(
                        TO_DATE(CAST(B.FIRST_MNTH_ID AS VARCHAR(6)) || '01', 'YYYYMMDD'),
                        -1
                    ),
                    'YYYYMM'
                ) AS INTEGER
            )
    GROUP BY
          B.FIRST_MNTH_ID
        , B.MSISDN
)
SEGMENTED BY HASH(FIRST_MNTH_ID, MSISDN) ALL NODES
;


