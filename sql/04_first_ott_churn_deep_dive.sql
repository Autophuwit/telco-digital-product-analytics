                       / TOPPING_BEFORE_REV
                     ) > 2.00
                 AND ( (TOPPING_AFTER_REV - TOPPING_BEFORE_REV)
                       / TOPPING_BEFORE_REV
                     ) <= 3.00
                  THEN '05|200–300%'

                ELSE '06|>300%'
            END
      END                                        AS UPLIFT_BAND
    , COUNT(DISTINCT SUBR_ID)                    AS NSUBR
    , SUM(COALESCE(ACTIVE_M01,0))                AS BASE_ACTIVE_M01
    , SUM(COALESCE(ACTIVE_M06,0))                AS ACTIVE_M06
    , (SUM(COALESCE(ACTIVE_M06,0)) * 1.00)
      / DECODE(
            NVL(SUM(COALESCE(ACTIVE_M01,0)),0)
          , 0, 1
          , SUM(COALESCE(ACTIVE_M01,0))
        )                                        AS SURVIVAL_RATE_M06
FROM SANDBOX.AUTO_LIFESTYLE_SUB_AGG_FIRST_OTT
WHERE TOPPING_FLAG      = 1
AND TOPPING_CHANNEL = 'Contact Center'
AND TOPPING_UPLIFT_FLAG = 1
GROUP BY
      UPLIFT_BAND
ORDER BY
      UPLIFT_BAND;	  
	
	
-- UPLIFT BAND WITH AVERAGE ARPU BEFORE AND AFTER
SELECT
      CASE
          WHEN TOPPING_BEFORE_REV IS NULL
            OR TOPPING_BEFORE_REV <= 0
            OR TOPPING_AFTER_REV IS NULL
            OR TOPPING_AFTER_REV < 0
            THEN '99|Unknown'
          ELSE
            CASE
                WHEN ( (TOPPING_AFTER_REV - TOPPING_BEFORE_REV)
                       / TOPPING_BEFORE_REV
                     ) <= 0
                  THEN '01|≤0%'

                WHEN ( (TOPPING_AFTER_REV - TOPPING_BEFORE_REV)
                       / TOPPING_BEFORE_REV
                     ) > 0
                 AND ( (TOPPING_AFTER_REV - TOPPING_BEFORE_REV)
                       / TOPPING_BEFORE_REV
                     ) <= 0.50
                  THEN '02|0–50%'

                WHEN ( (TOPPING_AFTER_REV - TOPPING_BEFORE_REV)
                       / TOPPING_BEFORE_REV
                     ) > 0.50
                 AND ( (TOPPING_AFTER_REV - TOPPING_BEFORE_REV)
                       / TOPPING_BEFORE_REV
                     ) <= 1.00
                  THEN '03|50–100%'

                WHEN ( (TOPPING_AFTER_REV - TOPPING_BEFORE_REV)
                       / TOPPING_BEFORE_REV
                     ) > 1.00
                 AND ( (TOPPING_AFTER_REV - TOPPING_BEFORE_REV)
                       / TOPPING_BEFORE_REV
                     ) <= 2.00
                  THEN '04|100–200%'

                WHEN ( (TOPPING_AFTER_REV - TOPPING_BEFORE_REV)
                       / TOPPING_BEFORE_REV
                     ) > 2.00
                 AND ( (TOPPING_AFTER_REV - TOPPING_BEFORE_REV)
                       / TOPPING_BEFORE_REV
                     ) <= 3.00
                  THEN '05|200–300%'

                ELSE '06|>300%'
            END
      END                                        AS UPLIFT_BAND

    , COUNT(DISTINCT SUBR_ID)                    AS NSUBR
    , SUM(COALESCE(ACTIVE_M01,0))                AS BASE_ACTIVE_M01
    , SUM(COALESCE(ACTIVE_M06,0))                AS ACTIVE_M06
    , (SUM(COALESCE(ACTIVE_M06,0)) * 1.00)
      / DECODE(
            NVL(SUM(COALESCE(ACTIVE_M01,0)),0)
          , 0, 1
          , SUM(COALESCE(ACTIVE_M01,0))
        )                                        AS SURVIVAL_RATE_M06

    /* NEW: Average ARPU before/after (keep NULLs ignored by AVG) */
    , AVG(CASE WHEN TOPPING_BEFORE_REV > 0 THEN TOPPING_BEFORE_REV END) AS AVG_TOPPING_BEFORE_REV
    , AVG(CASE WHEN TOPPING_AFTER_REV  >= 0 THEN TOPPING_AFTER_REV  END) AS AVG_TOPPING_AFTER_REV

FROM SANDBOX.AUTO_LIFESTYLE_SUB_AGG_FIRST_OTT
WHERE TOPPING_FLAG       = 1
  AND TOPPING_CHANNEL    = 'Contact Center'
  AND TOPPING_UPLIFT_FLAG = 1
GROUP BY
      UPLIFT_BAND
ORDER BY
      UPLIFT_BAND;