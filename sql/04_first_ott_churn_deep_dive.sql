(
    SELECT
          A.*
		, D.REF_RESRE_NBR AS MSISDN
		
		, CASE
              WHEN G.MSISDN IS NOT NULL THEN 1
			ELSE 0
          END                          AS GROSS_ADD_FLAG
		, G.SWON_TYPE            	   AS GROSS_ADD_SWON_TYPE
        , G.SWON_FLAG                  AS GROSS_ADD_SWON_FLAG
		, G.GA_CHANNEL                 AS GROSS_ADD_GA_CHANNEL
		, G.FIRST_ACTV_PP_CODE         AS GROSS_ADD_PP_CODE
		, G.FIRST_ACTV_PP_DESC         AS GROSS_ADD_PP_DESC
		, G.PP_TYPE                    AS GROSS_ADD_PP_TYPE
		, G.INFLOW_AMNT                AS GROSS_ADD_PACK_FEE
		, G.PC_EMP_CODE                AS GROSS_ADD_EMP_CD
        
		, CASE
              WHEN M.MSISDN IS NOT NULL THEN 1
              ELSE 0
          END                         AS CHANGE_MAIN_FLAG
        , M.F2F_FLG                   AS CHANGE_MAIN_F2F_FLG
        , M.CHANGE_MAIN_TYPE
        , M.CHANNEL                   AS CHANGE_MAIN_CHANNEL  
        , M.AGENT_EMP_ID              AS CHANGE_MAIN_EMP_ID
		
		, CASE
              WHEN C.PROD_KEY IS NOT NULL THEN 1
              ELSE 0
          END                         AS TOPPING_FLAG
		, C.CHANNEL                   AS TOPPING_CHANNEL    
        , C.EMP_CD                    AS TOPPING_EMP_CD

    FROM TEMP_SUB_PRO_FIRST_OTT A
    LEFT JOIN TEMP_SUB_CHANNEL C
        ON  A.FIRST_MNTH_ID = C.MNTH_ID
        AND A.SUBR_ID       = C.PROD_KEY
    LEFT JOIN TEMP_DIM_PROD D
        ON  A.SUBR_ID       = D.PROD_KEY
	LEFT JOIN SANDBOX.AUTO_LIFESTYLE_SUB_GROSS_ADD_FIRST_OTT G
        ON  A.FIRST_MNTH_ID = G.MNTH_ID
        AND D.REF_RESRE_NBR = G.MSISDN
		AND A.OTT_MERGE_PACK_CD = G.FIRST_ACTV_PP_CODE
    LEFT JOIN SANDBOX.AUTO_SUB_CHANGE_MAIN_FIRST_OTT M
        ON  D.REF_RESRE_NBR = M.MSISDN
        AND A.OTT_MERGE_PACK_CD = M.CUR_PP_NM
		AND A.FIRST_MNTH_ID = M.MNTH_ID
)
