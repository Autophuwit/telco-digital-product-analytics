DROP TABLE IF EXISTS TEMP_SUB_CHANNEL;

CREATE LOCAL TEMP TABLE TEMP_SUB_CHANNEL ON COMMIT PRESERVE ROWS AS 
(
SELECT 
	PROD_KEY
	, MNTH_ID
	, CASE WHEN UPPER(VAS.CHANNEL) IN ('CCR','SFF','UNIFY') AND UPPER(TRIM(COALESCE(PRT.GROUP_TDS_SPECIAL, PRT_EMP.GROUP_TDS_SPECIAL, SHOP.GROUP_TDS_SPECIAL))) IN ('BRAND_A SHOP','BRAND_B') THEN 'Branded Retail'
      WHEN UPPER(VAS.CHANNEL) IN ('CCR','SFF','UNIFY') AND UPPER(TRIM(COALESCE(PRT.GROUP_TDS_SPECIAL, PRT_EMP.GROUP_TDS_SPECIAL, SHOP.GROUP_TDS_SPECIAL,'OTHERS'))) IN ('TELESALES','OTHERS') THEN 'Contact Center'
      WHEN UPPER(VAS.CHANNEL) = 'OMX' AND UPPER(TRIM(COALESCE(PRT.GROUP_TDS_SPECIAL, PRT_EMP.GROUP_TDS_SPECIAL, SHOP.GROUP_TDS_SPECIAL))) IN ('TELESALES','SEGMENT','OTHERS') THEN 'Contact Center'
      WHEN UPPER(VAS.CHANNEL) = 'OMX' AND UPPER(NVL(VAS.PRTNR_CD, VAS.DLR_CD)) LIKE 'CTL%'  THEN 'Contact Center'
      WHEN UPPER(VAS.CHANNEL) IN ('CVM_CMP','DMP_ISERV2','OPAPP') THEN 'Digital App'
      WHEN UPPER(VAS.CHANNEL) LIKE '%IR%' THEN 'IR'
      ELSE 'Digital Other / Self Service' END AS CHANNEL
	, EMP_CD
FROM TEMP_FCT_VAS_CONTENT VAS
LEFT JOIN TEMP_PARTNER_CHANNEL PRT
	ON NVL(VAS.PRTNR_CD, VAS.DLR_CD)  = PRT.PARTNER_CODE
	AND PRT.RN = 1
	AND VAS.REQ_DT >= PRT.BEG_EFF_DATE
	AND VAS.REQ_DT < NVL(PRT.END_EFF_DATE, DATE '9999-12-31')
LEFT JOIN TEMP_PARTNER_CHANNEL_EMP PRT_EMP
	ON NVL(VAS.PRTNR_CD, VAS.DLR_CD) = PRT_EMP.EMP_ID
	AND PRT_EMP.RN = 1
LEFT JOIN (SELECT SH.EMP_ID
			,SH.SHOP_CD
			,PRT.GROUP_TDS_SPECIAL
			,ROW_NUMBER() OVER (PARTITION BY SH.EMP_ID ORDER BY SH.EMP_ID  DESC) AS RN 
			FROM EDW.SL_DIM_SHOP_STAFF SH
			LEFT JOIN TEMP_PARTNER_CHANNEL PRT
			ON PRT.PARTNER_CODE = SH.SHOP_CD) SHOP
	ON NVL(VAS.PRTNR_CD,VAS.DLR_CD) = SHOP.EMP_ID
	AND SHOP.RN = 1
)
SEGMENTED BY HASH(MNTH_ID, PROD_KEY) ALL NODES
;



