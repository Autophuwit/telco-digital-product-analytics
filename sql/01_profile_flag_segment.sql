DROP TABLE IF EXISTS TEMP_SUB_FLAG_SEGMENT_EXTENDED_AOU;

CREATE LOCAL TEMP TABLE TEMP_SUB_FLAG_SEGMENT_EXTENDED_AOU ON COMMIT PRESERVE ROWS AS 
(
SELECT 
	  P.*
	, A.AOU
	, CASE
       WHEN A.AOU <= 30*1  THEN 'A) 0M-1M'
	   WHEN A.AOU <= 30*2  THEN 'B) 1M-2M'
       WHEN A.AOU <= 30*3  THEN 'C) 2M-3M'
       WHEN A.AOU <= 30*6  THEN 'D) 3M-6M'
	   WHEN A.AOU <= 365*1 THEN 'E) 6M-1Y'
	   WHEN A.AOU <= 365*2 THEN 'F) 1Y-2Y'
	   WHEN A.AOU <= 365*3 THEN 'G) 2Y-3Y'
	   WHEN A.AOU <= 365*4 THEN 'H) 3Y-4Y'
	   WHEN A.AOU <= 365*5 THEN 'I) 4Y-5Y'
	   ELSE 'J) >5Y'
  END AS AOU_BAND
FROM TEMP_SUB_FLAG_SEGMENT_EXTENDED P
LEFT JOIN TEMP_SUB_AOU A
	ON P.MNTH_ID = A.MNTH_ID
	AND P.PROD_KEY = A.PROD_KEY
)
SEGMENTED BY HASH(MNTH_ID, PROD_KEY) ALL NODES
;

/* ============================================================
   8. LOAD GUARD - CHECK BEFORE REPLACING THE MONTH
   ============================================================ */
-- LOAD_OK = 1 only if the new month looks complete:
--   profile not empty, >= 90% of last month's subscribers, every subscriber has a flag row, revenue loaded
-- LOAD_OK = 0 -> step 9 deletes and inserts nothing, the month already loaded is kept
DROP TABLE IF EXISTS TEMP_LOAD_GUARD;

CREATE LOCAL TEMP TABLE TEMP_LOAD_GUARD ON COMMIT PRESERVE ROWS AS
(
SELECT
	  D.MNTH_ID
	, N.NSUBR_NEW
	, P.NSUBR_PREV
	, F.NSUBR_FLAG
	, R.NSUBR_REVN
	, CASE
		WHEN N.NSUBR_NEW = 0                                       THEN 0  -- source empty
		WHEN P.NSUBR_PREV > 0 AND N.NSUBR_NEW < P.NSUBR_PREV * 0.9 THEN 0  -- dropped > 10% vs last month
		WHEN F.NSUBR_FLAG <> N.NSUBR_NEW                           THEN 0  -- flag segment incomplete
		WHEN R.NSUBR_REVN = 0                                      THEN 0  -- revenue not loaded
		ELSE 1
	  END AS LOAD_OK
FROM TEMP_DATE D
CROSS JOIN (SELECT COUNT(DISTINCT PROD_KEY) AS NSUBR_NEW  FROM TEMP_SUB_PROFILE_MTH)              N
CROSS JOIN (SELECT COUNT(DISTINCT PROD_KEY) AS NSUBR_FLAG FROM TEMP_SUB_FLAG_SEGMENT_EXTENDED_AOU) F
CROSS JOIN (SELECT COUNT(DISTINCT PROD_KEY) AS NSUBR_REVN FROM TEMP_SUB_REVN_AGGREGATE)           R
CROSS JOIN (
	SELECT COUNT(DISTINCT PROD_KEY) AS NSUBR_PREV
	FROM SANDBOX.AUTO_SUB_PROFILE_MTH
