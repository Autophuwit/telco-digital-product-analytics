/* ============================================================
   0.1 CREATE RUN DATE
   ============================================================ */
-- Create Calendar and max date
DROP TABLE IF EXISTS TEMP_DATE;

CREATE LOCAL TEMP TABLE TEMP_DATE ON COMMIT PRESERVE ROWS AS
(
SELECT 
	 GREG_MTH_ID AS MNTH_ID 
	,MAX(GREG_DT_DT) AS MAX_RUN_DATE 
FROM EDW.DTN_GEOG_CLDR 
WHERE GREG_MTH_ID = 202511   -- 1) CHANGE MNTH_ID HERE
GROUP BY 1
ORDER BY GREG_MTH_ID 
)
SEGMENTED BY HASH(MNTH_ID) ALL NODES
;

-- CREATE VALIDATE TEMP RUN DATE
DROP TABLE IF EXISTS TEMP_VALIDATE_DATE;

CREATE LOCAL TEMP TABLE TEMP_VALIDATE_DATE ON COMMIT PRESERVE ROWS AS
(
SELECT
      MNTH_ID AS END_MNTH_ID
    , CAST(
          TO_CHAR(
              ADD_MONTHS(TO_DATE(CAST(MNTH_ID AS VARCHAR(6)) || '01', 'YYYYMMDD'), -5)
            , 'YYYYMM'
          ) AS INT
      ) AS START_MNTH_ID
FROM TEMP_DATE
)
SEGMENTED BY HASH(END_MNTH_ID) ALL NODES
;


/* ============================================================
   0.2 PRE VALIDATE DATA
   ============================================================ */
-- PRE VALIDATE EDW.DIM_PROD_KPI --> MAX DATE IN MONTH
SELECT 
	  VC_PAR_KEY
	, COUNT(*) AS TOTAL_SUBS
FROM EDW.DIM_PROD_KPI
WHERE CAST(TO_CHAR(VC_PAR_Key,'YYYYMM') AS INT) IN (SELECT MNTH_ID FROM TEMP_DATE)
GROUP BY VC_PAR_KEY 
ORDER BY VC_PAR_KEY
;

-- PRE VALIDATE EDW.DIM_ACCT --> MAX DATE 
SELECT 
	  VC_PAR_KEY
	, COUNT(*) AS TOTAL_SUBS
FROM EDW.DIM_ACCT
GROUP BY VC_PAR_KEY 
ORDER BY VC_PAR_KEY DESC
;

-- PRE VALIDATE EDW.DIM_PROD_MOL --> MAX DATE IN MONTH
SELECT 
	  VC_PAR_KEY
	, COUNT(*) AS TOTAL_SUBS
FROM EDW.DIM_PROD_MOL 
GROUP BY 1 
ORDER BY 1 DESC
;

-- PRE VALIDATE AGG_PREP_REV_SUBS_DAY --> MONTH
SELECT 
	  CAST(TO_CHAR(VC_PAR_Key,'YYYYMM') AS INT) AS MNTH_ID
	, SUM(
    NVL(CAST(TOT_MAIN_AMT AS NUMERIC(12,2)), 0)/1.07
	+ NVL(CAST(TOT_CASHBACK_AMT AS NUMERIC(12,2)), 0)
	+ CASE WHEN REV_CHNL IS NOT NULL THEN NVL(CAST(TOT_SRVC_RVN_AMT AS NUMERIC(12,2)),0)/1.07 ELSE NVL(CAST(TOT_TPPNG_CASH_AMT AS NUMERIC(12,2)), 0)/1.07 END
  ) AS REVN_AMNT
FROM EDW.AGG_PREP_REV_SUBS_DAY
CROSS JOIN TEMP_VALIDATE_DATE T
WHERE CAST(TO_CHAR(VC_PAR_Key,'YYYYMM') AS INT) BETWEEN T.START_MNTH_ID AND T.END_MNTH_ID
	AND RVN_IND = 1 
	AND NVL(TEST_IND, 0) <> 1
GROUP BY 1
ORDER BY 1
;

-- PRE VALIDATE FCT_INVC_PROD --> MONTH
SELECT 
	  AS_OF_MTH_KEY AS MNTH_ID
	, SUM(CAST(INVC_AMT AS DECIMAL(18, 6))) AS REVN_AMNT
FROM EDW.FCT_INVC_PROD
CROSS JOIN TEMP_VALIDATE_DATE T
WHERE INVC_TYP = 'BILL'
	AND PROD_CTGRY = 'Postpay'
	AND PROD_TYP_NM = 'Mobile'
	AND AS_OF_MTH_KEY BETWEEN T.START_MNTH_ID AND T.END_MNTH_ID
GROUP BY 1
ORDER BY 1
;

-- PRE VALIDATE EDW.FCT_VAS_CONTENT --> MONTH
SELECT 
	  CAST(FLOOR(PRO.REQ_TM_KEY_DAY / 100) AS INT) AS MNTH_ID
	, COUNT(*) AS TOTAL_SUBS
FROM EDW.FCT_VAS_CONTENT PRO
CROSS JOIN TEMP_VALIDATE_DATE T
Where 
	CAST(FLOOR(PRO.REQ_TM_KEY_DAY / 100) AS INT) BETWEEN T.START_MNTH_ID AND T.END_MNTH_ID
	AND PRO.PROD_CTGRY = 'Postpay' 
	AND UPPER(PRO.ACTION) LIKE 'BUY%'
GROUP BY 1
ORDER BY 1
;

-- PRE VALIDATE EDW.AGG_PREP_REV_SUBS_DAY --> MONTH
SELECT 
	  CAST(FLOOR(CALL_ST_TM_KEY_DAY/ 100) AS INT)
	, COUNT(*) AS TOTAL_SUBS
FROM EDW.AGG_PREP_REV_SUBS_DAY
CROSS JOIN TEMP_VALIDATE_DATE T
Where
	CAST(FLOOR(CALL_ST_TM_KEY_DAY / 100) AS INT) BETWEEN T.START_MNTH_ID AND T.END_MNTH_ID
	AND RVN_IND = 1
	AND NVL(TEST_IND, 0) <> 1
GROUP BY 1
ORDER BY 1 
;

-- PRE VALIDATE EDW.FCT_REV_SHARING --> MONTH
SELECT 
	  CAST(TO_CHAR(VC_PAR_KEY,'YYYYMM') AS INT) AS MNTH_ID
	, COUNT(*) AS TOTAL_SUBS
FROM EDW.FCT_REV_SHARING
CROSS JOIN TEMP_VALIDATE_DATE T
WHERE CAST(TO_CHAR(VC_PAR_KEY,'YYYYMM') AS INT) BETWEEN T.START_MNTH_ID AND T.END_MNTH_ID
	AND REV_TYPE IN ('DCB','CPA')
GROUP BY 1
ORDER BY 1
;

