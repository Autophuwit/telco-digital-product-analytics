-- CREATE THE PROFILE TABLE
DROP TABLE IF EXISTS TEMP_SUB_PROFILE_MTH;

CREATE LOCAL TEMP TABLE TEMP_SUB_PROFILE_MTH ON COMMIT PRESERVE ROWS AS 
(
SELECT DISTINCT
	  CAST(TO_CHAR(P.VC_PAR_KEY,'YYYYMM') AS INT) AS MNTH_ID
	, P.PROD_KEY
	, P.PROD_CTGRY
	, P.CUR_PP_NM
	, CASE WHEN P.PROD_CTGRY = 'Prepay' THEN 
		(CASE
		WHEN UPPER(S.GP_SIM_TYPE) IN ('INTER SIM','TOURIST SIM','TRAVEL SIM') OR S.PP_CODE LIKE '%RIR%' THEN 'Tourist SIM'
		WHEN S.N2P = 'MIGRANT'                                                                        THEN 'Migrant SIM'
		ELSE                                                                                             'Mass SIM'
		END)
		ELSE COALESCE(AA.ACCT_TYP, AB.ACCT_TYP) END AS SIM_TYPE
FROM EDW.DIM_PROD_MOL P	
LEFT JOIN EDW.DIM_PREP_PRICE_PLAN S
	ON P.CUR_PP_NM = S.PP_CODE
LEFT JOIN TEMP_SUB_DIM_ACCT AA
	ON P.CUST_ACCT_KEY = AA.CUST_ACCT_KEY
LEFT JOIN TEMP_SUB_DIM_ACCT AB
	ON P.CUST_BAGG_KEY = AB.CUST_ACCT_KEY
LEFT JOIN TEMP_SUB_DIM_PROD_KPI KPI
	ON P.PROD_KEY = KPI.PROD_KEY
	AND P.VC_PAR_KEY = KPI.VC_PAR_KEY
WHERE  P.DWH_PROD_STAT IN ('A','E','D')
    AND P.PROD_CTGRY IN ('Postpay','Prepay')
    AND NVL(KPI.SILENT_STAT,'X') <> 'Y'
	AND (P.PROD_CTGRY <> 'Postpay' OR COALESCE(AA.ACCT_TYP, AB.ACCT_TYP) = 'I')
	AND P.VC_PAR_KEY IN (SELECT MAX_RUN_DATE FROM TEMP_DATE) 
)
SEGMENTED BY HASH(MNTH_ID, PROD_KEY) ALL NODES
;

