/* ============================================================
   6. MERGE AND FLAG SEGMENT TABLE
   ============================================================ */ 
DROP TABLE IF EXISTS TEMP_SUB_MERGE_SEGMENT;

CREATE LOCAL TEMP TABLE TEMP_SUB_MERGE_SEGMENT ON COMMIT PRESERVE ROWS AS 
(
SELECT 
	  PRO.MNTH_ID
	, PRO.PROD_KEY
	, PRO.PROD_CTGRY
	, PRO.SIM_TYPE
	, CASE WHEN (MO.PROD_KEY IS NOT NULL) OR (TT.PROD_KEY IS NOT NULL) THEN 1 ELSE 0 END AS OTT_FLAG
	, CASE WHEN (MG.PROD_KEY IS NOT NULL) OR (TG.PROD_KEY IS NOT NULL) THEN 1 ELSE 0 END AS GAME_FLAG
	, CASE WHEN (MU.PROD_KEY IS NOT NULL) OR (TU.PROD_KEY IS NOT NULL) THEN 1 ELSE 0 END AS UP2U_FLAG
	, CASE WHEN (MS.PROD_KEY IS NOT NULL) OR (TS.PROD_KEY IS NOT NULL) THEN 1 ELSE 0 END AS SECURE_FLAG
	, CASE WHEN  DCB.PROD_KEY IS NOT NULL THEN 1 ELSE 0 END AS DCB_FLAG
	, CASE WHEN  CPA.PROD_KEY IS NOT NULL THEN 1 ELSE 0 END AS CPA_FLAG	
FROM TEMP_SUB_PROFILE_MTH PRO
LEFT JOIN TEMP_SUB_MAIN_OTT MO
	ON PRO.MNTH_ID = MO.MNTH_ID
	AND PRO.PROD_KEY = MO.PROD_KEY
LEFT JOIN TEMP_SUB_MAIN_GAME MG
	ON PRO.MNTH_ID = MG.MNTH_ID
	AND PRO.PROD_KEY = MG.PROD_KEY
LEFT JOIN TEMP_SUB_MAIN_UP2U MU
	ON PRO.MNTH_ID = MU.MNTH_ID
	AND PRO.PROD_KEY = MU.PROD_KEY
LEFT JOIN TEMP_SUB_MAIN_SECURE MS
	ON PRO.MNTH_ID = MS.MNTH_ID
	AND PRO.PROD_KEY = MS.PROD_KEY
LEFT JOIN TEMP_SUB_TOP_OTT TT
	ON PRO.MNTH_ID = TT.MNTH_ID
	AND PRO.PROD_KEY = TT.PROD_KEY
LEFT JOIN TEMP_SUB_TOP_GAME TG
	ON PRO.MNTH_ID = TG.MNTH_ID
	AND PRO.PROD_KEY = TG.PROD_KEY
LEFT JOIN TEMP_SUB_TOP_UP2U TU
	ON PRO.MNTH_ID = TU.MNTH_ID
	AND PRO.PROD_KEY = TU.PROD_KEY
LEFT JOIN TEMP_SUB_TOP_SECURE TS
	ON PRO.MNTH_ID = TS.MNTH_ID
	AND PRO.PROD_KEY = TS.PROD_KEY
LEFT JOIN TEMP_SUB_DCB DCB
	ON PRO.MNTH_ID = DCB.MNTH_ID
	AND PRO.PROD_KEY = DCB.PROD_KEY
LEFT JOIN TEMP_SUB_CPA CPA
	ON PRO.MNTH_ID = CPA.MNTH_ID
	AND PRO.PROD_KEY = CPA.PROD_KEY
)
SEGMENTED BY HASH(MNTH_ID, PROD_KEY) ALL NODES
;


