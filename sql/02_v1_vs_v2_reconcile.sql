/* ============================================================
   PARALLEL RUN - 02 v1 (WIDE TABLE) vs 02 v2 (LONG TABLE)
   ------------------------------------------------------------
   Used while switching 03_monthly_report_export.sql from v1 to v2:
   run both 02 scripts every month from PARALLEL_START (first month v2 ran), then this file.
       vsql -v PARALLEL_START=202512 -v RUN_MNTH=202602 -f 02_v1_vs_v2_reconcile.sql
   Only cohorts from PARALLEL_START on are compared - v2 has no history before its first run.

   Compared cell by cell: one row per cohort member x month number, i.e. per activity month.
   Expected differences
     - REVENUE: v1 SUMs revenue over every profile row of a subscriber, so a PROD_KEY that is
       duplicated in the profile of a month is counted twice in that month; v2 takes it once (MAX).
       R2 matches every revenue difference to a duplicate in the SAME activity month -
       anything else is "UNEXPLAINED".
     - ACTIVE_CHURN is not compared: it is 0 in both versions (kept for the table layout).
   Everything else (cohort members, ACTIVE, ACTIVE_DIGITAL, ACTIVE_CALLER) must match exactly.
   ============================================================ */


/* ============================================================
   1. v1 WIDE TABLE -> LONG (SAME GRAIN AS THE v2 TABLE)
   ============================================================ */
DROP TABLE IF EXISTS TEMP_RECON_V1_LONG;

CREATE LOCAL TEMP TABLE TEMP_RECON_V1_LONG ON COMMIT PRESERVE ROWS AS
(
SELECT
	  W.MNTH_ID AS COHORT_MNTH_ID
	, W.PROD_KEY
	, M.MONTH_NO
	, CAST(TO_CHAR(ADD_MONTHS(TO_DATE(CAST(W.MNTH_ID AS VARCHAR(6)), 'YYYYMM'), M.MONTH_NO - 1), 'YYYYMM') AS INT) AS ACTIVITY_MNTH_ID
	, CASE M.MONTH_NO
		WHEN 1  THEN W.ACTIVE_M01
		WHEN 2  THEN W.ACTIVE_M02
		WHEN 3  THEN W.ACTIVE_M03
		WHEN 4  THEN W.ACTIVE_M04
		WHEN 5  THEN W.ACTIVE_M05
		WHEN 6  THEN W.ACTIVE_M06
		WHEN 7  THEN W.ACTIVE_M07
		WHEN 8  THEN W.ACTIVE_M08
		WHEN 9  THEN W.ACTIVE_M09
		WHEN 10 THEN W.ACTIVE_M10
		WHEN 11 THEN W.ACTIVE_M11
		WHEN 12 THEN W.ACTIVE_M12
	  END AS ACTIVE
	, CASE M.MONTH_NO
		WHEN 1  THEN W.REVN_AMNT_M01
		WHEN 2  THEN W.REVN_AMNT_M02
		WHEN 3  THEN W.REVN_AMNT_M03
		WHEN 4  THEN W.REVN_AMNT_M04
		WHEN 5  THEN W.REVN_AMNT_M05
		WHEN 6  THEN W.REVN_AMNT_M06
		WHEN 7  THEN W.REVN_AMNT_M07
		WHEN 8  THEN W.REVN_AMNT_M08
		WHEN 9  THEN W.REVN_AMNT_M09
		WHEN 10 THEN W.REVN_AMNT_M10
		WHEN 11 THEN W.REVN_AMNT_M11
		WHEN 12 THEN W.REVN_AMNT_M12
	  END AS REVN_AMNT
	, CASE M.MONTH_NO
		WHEN 1  THEN W.ACTIVE_DIGITAL_M01
		WHEN 2  THEN W.ACTIVE_DIGITAL_M02
		WHEN 3  THEN W.ACTIVE_DIGITAL_M03
		WHEN 4  THEN W.ACTIVE_DIGITAL_M04
		WHEN 5  THEN W.ACTIVE_DIGITAL_M05
		WHEN 6  THEN W.ACTIVE_DIGITAL_M06
		WHEN 7  THEN W.ACTIVE_DIGITAL_M07
		WHEN 8  THEN W.ACTIVE_DIGITAL_M08
		WHEN 9  THEN W.ACTIVE_DIGITAL_M09
		WHEN 10 THEN W.ACTIVE_DIGITAL_M10
		WHEN 11 THEN W.ACTIVE_DIGITAL_M11
		WHEN 12 THEN W.ACTIVE_DIGITAL_M12
	  END AS ACTIVE_DIGITAL
	, CASE M.MONTH_NO
		WHEN 1  THEN W.ACTIVE_CALLER_M01
		WHEN 2  THEN W.ACTIVE_CALLER_M02
		WHEN 3  THEN W.ACTIVE_CALLER_M03
		WHEN 4  THEN W.ACTIVE_CALLER_M04
		WHEN 5  THEN W.ACTIVE_CALLER_M05
		WHEN 6  THEN W.ACTIVE_CALLER_M06
		WHEN 7  THEN W.ACTIVE_CALLER_M07
		WHEN 8  THEN W.ACTIVE_CALLER_M08
		WHEN 9  THEN W.ACTIVE_CALLER_M09
		WHEN 10 THEN W.ACTIVE_CALLER_M10
		WHEN 11 THEN W.ACTIVE_CALLER_M11
		WHEN 12 THEN W.ACTIVE_CALLER_M12
	  END AS ACTIVE_CALLER
FROM SANDBOX.AUTO_LIFESTYLE_SUB_SEGMENT_SURVIVAL_ACTIVE_CALLER W
CROSS JOIN (
	SELECT 1 AS MONTH_NO
	UNION ALL SELECT 2
	UNION ALL SELECT 3
	UNION ALL SELECT 4
	UNION ALL SELECT 5
	UNION ALL SELECT 6
	UNION ALL SELECT 7
	UNION ALL SELECT 8
	UNION ALL SELECT 9
	UNION ALL SELECT 10
	UNION ALL SELECT 11
	UNION ALL SELECT 12
) M
WHERE W.MNTH_ID BETWEEN :PARALLEL_START AND :RUN_MNTH
-- months after RUN_MNTH are not measured yet (0 in v1, no row in v2)
AND M.MONTH_NO <= DATEDIFF('month', TO_DATE(CAST(W.MNTH_ID AS VARCHAR(6)), 'YYYYMM')
                                  , TO_DATE(CAST(:RUN_MNTH AS VARCHAR(6)), 'YYYYMM')) + 1
)
SEGMENTED BY HASH(PROD_KEY) ALL NODES
;


/* ============================================================
   2. CELL-LEVEL COMPARE
   ============================================================ */
DROP TABLE IF EXISTS TEMP_RECON_CELL;

CREATE LOCAL TEMP TABLE TEMP_RECON_CELL ON COMMIT PRESERVE ROWS AS
(
SELECT
	  COALESCE(A.COHORT_MNTH_ID, B.COHORT_MNTH_ID)       AS COHORT_MNTH_ID
	, COALESCE(A.PROD_KEY, B.PROD_KEY)                   AS PROD_KEY
	, COALESCE(A.ACTIVITY_MNTH_ID, B.ACTIVITY_MNTH_ID)   AS ACTIVITY_MNTH_ID
	, CASE WHEN A.PROD_KEY IS NOT NULL THEN 1 ELSE 0 END AS IN_V1
	, CASE WHEN B.PROD_KEY IS NOT NULL THEN 1 ELSE 0 END AS IN_V2
	, CASE WHEN A.ACTIVE         <> B.ACTIVE
		    OR A.ACTIVE_DIGITAL <> B.ACTIVE_DIGITAL
		    OR A.ACTIVE_CALLER  <> B.ACTIVE_CALLER  THEN 1 ELSE 0 END AS FLAG_DIFF
	, ABS(COALESCE(A.REVN_AMNT, 0) - COALESCE(B.REVN_AMNT, 0))  AS REVN_DIFF
	, COALESCE(A.REVN_AMNT, 0)                           AS REVN_V1
	, COALESCE(B.REVN_AMNT, 0)                           AS REVN_V2
FROM TEMP_RECON_V1_LONG A
FULL OUTER JOIN (
	SELECT * FROM SANDBOX.AUTO_LIFESTYLE_SUB_SURVIVAL_LONG
	WHERE COHORT_MNTH_ID BETWEEN :PARALLEL_START AND :RUN_MNTH
) B
	ON A.PROD_KEY = B.PROD_KEY
	AND A.COHORT_MNTH_ID = B.COHORT_MNTH_ID
	AND A.MONTH_NO = B.MONTH_NO
)
SEGMENTED BY HASH(PROD_KEY) ALL NODES
;


/* ============================================================
   3. REVENUE DIFFERENCES AND THEIR REASON (SAME ACTIVITY MONTH)
   ============================================================ */
DROP TABLE IF EXISTS TEMP_RECON_REVN;

CREATE LOCAL TEMP TABLE TEMP_RECON_REVN ON COMMIT PRESERVE ROWS AS
(
SELECT
	  C.COHORT_MNTH_ID
	, C.ACTIVITY_MNTH_ID
	, C.PROD_KEY
	, C.REVN_DIFF
	, CASE WHEN D.PROD_KEY IS NOT NULL THEN 'duplicate profile row' ELSE 'UNEXPLAINED' END AS REASON
FROM TEMP_RECON_CELL C
LEFT JOIN (
	SELECT MNTH_ID, PROD_KEY
	FROM SANDBOX.AUTO_SUB_PROFILE_MTH
	WHERE MNTH_ID BETWEEN :PARALLEL_START AND :RUN_MNTH
	GROUP BY 1, 2
	HAVING COUNT(*) > 1
) D
	ON C.PROD_KEY = D.PROD_KEY
	AND C.ACTIVITY_MNTH_ID = D.MNTH_ID
WHERE C.IN_V1 = 1 AND C.IN_V2 = 1
AND C.REVN_DIFF > 0.01
)
SEGMENTED BY HASH(PROD_KEY) ALL NODES
;


/* ============================================================
   4. RESULT
   ============================================================ */
-- R1. per cohort month (cells = cohort member x measured month)
SELECT
	  COHORT_MNTH_ID
	, COUNT(DISTINCT CASE WHEN IN_V1 = 1 THEN PROD_KEY END)     AS MEMBERS_V1
	, COUNT(DISTINCT CASE WHEN IN_V2 = 1 THEN PROD_KEY END)     AS MEMBERS_V2
	, SUM(CASE WHEN IN_V1 = 1 AND IN_V2 = 0 THEN 1 ELSE 0 END)  AS CELLS_ONLY_IN_V1
	, SUM(CASE WHEN IN_V1 = 0 AND IN_V2 = 1 THEN 1 ELSE 0 END)  AS CELLS_ONLY_IN_V2
	, SUM(FLAG_DIFF)                                             AS CELLS_FLAG_DIFF
	, SUM(CASE WHEN REVN_DIFF > 0.01 THEN 1 ELSE 0 END)         AS CELLS_REVN_DIFF
	, ROUND(SUM(REVN_V1), 2)                                     AS REVN_V1
	, ROUND(SUM(REVN_V2), 2)                                     AS REVN_V2
FROM TEMP_RECON_CELL
GROUP BY 1
ORDER BY 1
;

-- R2. revenue differences by reason (expect "duplicate profile row" only)
--     size of the v1 bug: N_SUBR subscribers, REVN_DIFF revenue counted twice
SELECT
	  REASON
	, COUNT(*)                  AS N_CELLS
	, COUNT(DISTINCT PROD_KEY)  AS N_SUBR
	, ROUND(SUM(REVN_DIFF), 2)  AS REVN_DIFF
FROM TEMP_RECON_REVN
GROUP BY 1
ORDER BY 1
;

-- SUMMARY
SELECT
	  :RUN_MNTH AS MNTH_ID
	, CASE
		WHEN (SELECT COUNT(*) FROM TEMP_RECON_CELL WHERE IN_V1 = 0 OR IN_V2 = 0 OR FLAG_DIFF = 1) = 0
		 AND (SELECT COUNT(*) FROM TEMP_RECON_REVN WHERE REASON = 'UNEXPLAINED') = 0
		THEN 'MATCH - only the expected revenue fix differs'
		ELSE 'DIFFERENT - CHECK R1 / R2'
	  END AS RESULT
;
