/* ============================================================
   PARALLEL RUN - 02 v1 (WIDE TABLE) vs 02 v2 (LONG TABLE + VIEW _V)
   ------------------------------------------------------------
   Used while switching 03_monthly_report_export.sql from v1 to v2:
   run both 02 scripts every month from PARALLEL_START (first month v2 ran), then this file.
       vsql -v PARALLEL_START=202512 -v RUN_MNTH=202602 -f 02_v1_vs_v2_reconcile.sql
   Only cohorts from PARALLEL_START on are compared - v2 has no history before its first run.

   Expected differences
     - REVENUE: v1 SUMs revenue over every profile row of a subscriber, so a PROD_KEY that is
       duplicated in the profile is counted twice; v2 takes it once (MAX).
       R2 lists every revenue difference with its reason - each one should be "duplicate profile row".
     - ACTIVE_CHURN is not compared: it is 0 in both versions (kept for the table layout).
   Everything else (cohort members, ACTIVE, ACTIVE_DIGITAL, ACTIVE_CALLER) must match exactly.
   ============================================================ */


/* ============================================================
   1. ROW-LEVEL COMPARE (ONE ROW PER COHORT MEMBER)
   ============================================================ */
DROP TABLE IF EXISTS TEMP_RECON_ROW;

CREATE LOCAL TEMP TABLE TEMP_RECON_ROW ON COMMIT PRESERVE ROWS AS
(
SELECT
	  COALESCE(W.MNTH_ID, V.MNTH_ID)   AS COHORT_MNTH_ID
	, COALESCE(W.PROD_KEY, V.PROD_KEY) AS PROD_KEY
	, CASE WHEN W.PROD_KEY IS NOT NULL THEN 1 ELSE 0 END AS IN_V1
	, CASE WHEN V.PROD_KEY IS NOT NULL THEN 1 ELSE 0 END AS IN_V2
	-- number of M01..M12 flag cells that differ (ACTIVE, ACTIVE_DIGITAL, ACTIVE_CALLER)
	, (
		  ABS(W.ACTIVE_M01 - V.ACTIVE_M01) + ABS(W.ACTIVE_DIGITAL_M01 - V.ACTIVE_DIGITAL_M01) + ABS(W.ACTIVE_CALLER_M01 - V.ACTIVE_CALLER_M01)
		+ ABS(W.ACTIVE_M02 - V.ACTIVE_M02) + ABS(W.ACTIVE_DIGITAL_M02 - V.ACTIVE_DIGITAL_M02) + ABS(W.ACTIVE_CALLER_M02 - V.ACTIVE_CALLER_M02)
		+ ABS(W.ACTIVE_M03 - V.ACTIVE_M03) + ABS(W.ACTIVE_DIGITAL_M03 - V.ACTIVE_DIGITAL_M03) + ABS(W.ACTIVE_CALLER_M03 - V.ACTIVE_CALLER_M03)
		+ ABS(W.ACTIVE_M04 - V.ACTIVE_M04) + ABS(W.ACTIVE_DIGITAL_M04 - V.ACTIVE_DIGITAL_M04) + ABS(W.ACTIVE_CALLER_M04 - V.ACTIVE_CALLER_M04)
		+ ABS(W.ACTIVE_M05 - V.ACTIVE_M05) + ABS(W.ACTIVE_DIGITAL_M05 - V.ACTIVE_DIGITAL_M05) + ABS(W.ACTIVE_CALLER_M05 - V.ACTIVE_CALLER_M05)
		+ ABS(W.ACTIVE_M06 - V.ACTIVE_M06) + ABS(W.ACTIVE_DIGITAL_M06 - V.ACTIVE_DIGITAL_M06) + ABS(W.ACTIVE_CALLER_M06 - V.ACTIVE_CALLER_M06)
		+ ABS(W.ACTIVE_M07 - V.ACTIVE_M07) + ABS(W.ACTIVE_DIGITAL_M07 - V.ACTIVE_DIGITAL_M07) + ABS(W.ACTIVE_CALLER_M07 - V.ACTIVE_CALLER_M07)
		+ ABS(W.ACTIVE_M08 - V.ACTIVE_M08) + ABS(W.ACTIVE_DIGITAL_M08 - V.ACTIVE_DIGITAL_M08) + ABS(W.ACTIVE_CALLER_M08 - V.ACTIVE_CALLER_M08)
		+ ABS(W.ACTIVE_M09 - V.ACTIVE_M09) + ABS(W.ACTIVE_DIGITAL_M09 - V.ACTIVE_DIGITAL_M09) + ABS(W.ACTIVE_CALLER_M09 - V.ACTIVE_CALLER_M09)
		+ ABS(W.ACTIVE_M10 - V.ACTIVE_M10) + ABS(W.ACTIVE_DIGITAL_M10 - V.ACTIVE_DIGITAL_M10) + ABS(W.ACTIVE_CALLER_M10 - V.ACTIVE_CALLER_M10)
		+ ABS(W.ACTIVE_M11 - V.ACTIVE_M11) + ABS(W.ACTIVE_DIGITAL_M11 - V.ACTIVE_DIGITAL_M11) + ABS(W.ACTIVE_CALLER_M11 - V.ACTIVE_CALLER_M11)
		+ ABS(W.ACTIVE_M12 - V.ACTIVE_M12) + ABS(W.ACTIVE_DIGITAL_M12 - V.ACTIVE_DIGITAL_M12) + ABS(W.ACTIVE_CALLER_M12 - V.ACTIVE_CALLER_M12)
	  ) AS FLAG_CELLS_DIFF
	-- absolute revenue difference over M01..M12
	, (
		  ABS(COALESCE(W.REVN_AMNT_M01, 0) - COALESCE(V.REVN_AMNT_M01, 0))
		+ ABS(COALESCE(W.REVN_AMNT_M02, 0) - COALESCE(V.REVN_AMNT_M02, 0))
		+ ABS(COALESCE(W.REVN_AMNT_M03, 0) - COALESCE(V.REVN_AMNT_M03, 0))
		+ ABS(COALESCE(W.REVN_AMNT_M04, 0) - COALESCE(V.REVN_AMNT_M04, 0))
		+ ABS(COALESCE(W.REVN_AMNT_M05, 0) - COALESCE(V.REVN_AMNT_M05, 0))
		+ ABS(COALESCE(W.REVN_AMNT_M06, 0) - COALESCE(V.REVN_AMNT_M06, 0))
		+ ABS(COALESCE(W.REVN_AMNT_M07, 0) - COALESCE(V.REVN_AMNT_M07, 0))
		+ ABS(COALESCE(W.REVN_AMNT_M08, 0) - COALESCE(V.REVN_AMNT_M08, 0))
		+ ABS(COALESCE(W.REVN_AMNT_M09, 0) - COALESCE(V.REVN_AMNT_M09, 0))
		+ ABS(COALESCE(W.REVN_AMNT_M10, 0) - COALESCE(V.REVN_AMNT_M10, 0))
		+ ABS(COALESCE(W.REVN_AMNT_M11, 0) - COALESCE(V.REVN_AMNT_M11, 0))
		+ ABS(COALESCE(W.REVN_AMNT_M12, 0) - COALESCE(V.REVN_AMNT_M12, 0))
	  ) AS REVN_DIFF
	, ( COALESCE(W.REVN_AMNT_M01, 0) + COALESCE(W.REVN_AMNT_M02, 0) + COALESCE(W.REVN_AMNT_M03, 0) + COALESCE(W.REVN_AMNT_M04, 0) + COALESCE(W.REVN_AMNT_M05, 0) + COALESCE(W.REVN_AMNT_M06, 0)
		+ COALESCE(W.REVN_AMNT_M07, 0) + COALESCE(W.REVN_AMNT_M08, 0) + COALESCE(W.REVN_AMNT_M09, 0) + COALESCE(W.REVN_AMNT_M10, 0) + COALESCE(W.REVN_AMNT_M11, 0) + COALESCE(W.REVN_AMNT_M12, 0) ) AS REVN_V1
	, ( COALESCE(V.REVN_AMNT_M01, 0) + COALESCE(V.REVN_AMNT_M02, 0) + COALESCE(V.REVN_AMNT_M03, 0) + COALESCE(V.REVN_AMNT_M04, 0) + COALESCE(V.REVN_AMNT_M05, 0) + COALESCE(V.REVN_AMNT_M06, 0)
		+ COALESCE(V.REVN_AMNT_M07, 0) + COALESCE(V.REVN_AMNT_M08, 0) + COALESCE(V.REVN_AMNT_M09, 0) + COALESCE(V.REVN_AMNT_M10, 0) + COALESCE(V.REVN_AMNT_M11, 0) + COALESCE(V.REVN_AMNT_M12, 0) ) AS REVN_V2
FROM (
	SELECT * FROM SANDBOX.AUTO_LIFESTYLE_SUB_SEGMENT_SURVIVAL_ACTIVE_CALLER
	WHERE MNTH_ID BETWEEN :PARALLEL_START AND :RUN_MNTH
) W
FULL OUTER JOIN (
	SELECT * FROM SANDBOX.AUTO_LIFESTYLE_SUB_SEGMENT_SURVIVAL_ACTIVE_CALLER_V
	WHERE MNTH_ID BETWEEN :PARALLEL_START AND :RUN_MNTH
) V
	ON W.MNTH_ID = V.MNTH_ID
	AND W.PROD_KEY = V.PROD_KEY
)
SEGMENTED BY HASH(PROD_KEY) ALL NODES
;


/* ============================================================
   2. REVENUE DIFFERENCES AND THEIR REASON
   ============================================================ */
DROP TABLE IF EXISTS TEMP_RECON_REVN;

CREATE LOCAL TEMP TABLE TEMP_RECON_REVN ON COMMIT PRESERVE ROWS AS
(
SELECT
	  R.COHORT_MNTH_ID
	, R.PROD_KEY
	, R.REVN_DIFF
	, CASE WHEN D.PROD_KEY IS NOT NULL THEN 'duplicate profile row' ELSE 'UNEXPLAINED' END AS REASON
FROM TEMP_RECON_ROW R
LEFT JOIN (
	SELECT DISTINCT PROD_KEY
	FROM (
		SELECT MNTH_ID, PROD_KEY
		FROM SANDBOX.AUTO_SUB_PROFILE_MTH
		WHERE MNTH_ID BETWEEN :PARALLEL_START AND :RUN_MNTH
		GROUP BY 1, 2
		HAVING COUNT(*) > 1
	) X
) D
	ON R.PROD_KEY = D.PROD_KEY
WHERE R.IN_V1 = 1 AND R.IN_V2 = 1
AND R.REVN_DIFF > 0.01
)
SEGMENTED BY HASH(PROD_KEY) ALL NODES
;


/* ============================================================
   3. RESULT
   ============================================================ */
-- R1. per cohort month
SELECT
	  COHORT_MNTH_ID
	, SUM(IN_V1)                                                     AS N_V1
	, SUM(IN_V2)                                                     AS N_V2
	, SUM(CASE WHEN IN_V1 = 1 AND IN_V2 = 0 THEN 1 ELSE 0 END)      AS ONLY_IN_V1
	, SUM(CASE WHEN IN_V1 = 0 AND IN_V2 = 1 THEN 1 ELSE 0 END)      AS ONLY_IN_V2
	, SUM(CASE WHEN FLAG_CELLS_DIFF > 0 THEN 1 ELSE 0 END)          AS ROWS_FLAG_DIFF
	, SUM(CASE WHEN REVN_DIFF > 0.01 THEN 1 ELSE 0 END)             AS ROWS_REVN_DIFF
	, ROUND(SUM(REVN_V1), 2)                                         AS REVN_V1
	, ROUND(SUM(REVN_V2), 2)                                         AS REVN_V2
FROM TEMP_RECON_ROW
GROUP BY 1
ORDER BY 1
;

-- R2. revenue differences by reason (expect "duplicate profile row" only)
SELECT
	  REASON
	, COUNT(*)                AS N_ROWS
	, ROUND(SUM(REVN_DIFF), 2) AS REVN_DIFF
FROM TEMP_RECON_REVN
GROUP BY 1
ORDER BY 1
;

-- SUMMARY
SELECT
	  :RUN_MNTH AS MNTH_ID
	, CASE
		WHEN (SELECT COUNT(*) FROM TEMP_RECON_ROW WHERE IN_V1 = 0 OR IN_V2 = 0 OR FLAG_CELLS_DIFF > 0) = 0
		 AND (SELECT COUNT(*) FROM TEMP_RECON_REVN WHERE REASON = 'UNEXPLAINED') = 0
		THEN 'MATCH - only the expected revenue fix differs'
		ELSE 'DIFFERENT - CHECK R1 / R2'
	  END AS RESULT
;
