/* ============================================================
   0.1 CREATE RUN DATE
   ============================================================ */
-- Create Calendar and max date
DROP TABLE IF EXISTS TEMP_DATE;

CREATE LOCAL TEMP TABLE TEMP_DATE ON COMMIT PRESERVE ROWS AS
(
SELECT 
	 GREG_MTH_ID AS MNTH_ID 
	,MAX(GREG_DT_DT) AS MAX_RUN_DATE 
FROM EDW.DTN_GEOG_CLDR 
WHERE GREG_MTH_ID = 202511   -- 1) CHANGE MNTH_ID HERE
GROUP BY 1
ORDER BY GREG_MTH_ID 
)
SEGMENTED BY HASH(MNTH_ID) ALL NODES
;


/* ============================================================
   1. ADD ACTIVE CALLER 
   ============================================================ */ 
DROP TABLE IF EXISTS TEMP_SUB_DIM_PROD_KPI;

CREATE LOCAL TEMP TABLE TEMP_SUB_DIM_PROD_KPI ON COMMIT PRESERVE ROWS AS 
(
SELECT DISTINCT
	  VC_PAR_KEY
	, PROD_KEY
	, SILENT_STAT
FROM EDW.DIM_PROD_KPI
WHERE VC_PAR_KEY IN (SELECT MAX_RUN_DATE FROM TEMP_DATE)
AND ACTV_CALLER_IND = 1
)
SEGMENTED BY HASH(VC_PAR_KEY, PROD_KEY) ALL NODES
;

DROP TABLE IF EXISTS TEMP_SUB_PROFILE_MTH_ACTIVE_CALLER;

CREATE LOCAL TEMP TABLE TEMP_SUB_PROFILE_MTH_ACTIVE_CALLER ON COMMIT PRESERVE ROWS AS 
(
SELECT 
	  PRO.*
	, CASE WHEN KPI.PROD_KEY IS NOT NULL THEN 1 ELSE 0 END AS ACTIVE_CALLER
FROM TEMP_SUB_PROFILE_MTH PRO
LEFT JOIN TEMP_SUB_DIM_PROD_KPI KPI
	ON PRO.PROD_KEY = KPI.PROD_KEY
)
SEGMENTED BY HASH(MNTH_ID, PROD_KEY) ALL NODES
;

/* ============================================================
   2. MERGE PROFILE WITH REVENUE AND ACTIVE_DIGITAL AND OTHER TABLE  
   ============================================================ */ 
-- Merge Active Profile With Revenue
DROP TABLE IF EXISTS TEMP_SUB_PROFILE_REV;

CREATE LOCAL TEMP TABLE TEMP_SUB_PROFILE_REV ON COMMIT PRESERVE ROWS AS 
(
Select 
	  PRO.MNTH_ID
	, PRO.PROD_KEY
	, 1 AS ACTIVE
	, PRO.ACTIVE_CALLER
	, REV.REVN_AMNT
FROM TEMP_SUB_PROFILE_MTH_ACTIVE_CALLER PRO
LEFT JOIN TEMP_SUB_REVN_AGGREGATE REV
	ON PRO.MNTH_ID = REV.MNTH_ID
	AND PRO.PROD_KEY = REV.PROD_KEY
)
SEGMENTED BY HASH(MNTH_ID, PROD_KEY) ALL NODES
;

-- Merge Active Profile With Active Digital
DROP TABLE IF EXISTS TEMP_SUB_PROFILE_ACTIVE_DIGITAL;

CREATE LOCAL TEMP TABLE TEMP_SUB_PROFILE_ACTIVE_DIGITAL ON COMMIT PRESERVE ROWS AS 
(
SELECT
	  PRO.MNTH_ID
	, PRO.PROD_KEY
	, DIGI.TOTAL_DIGIT AS ACTIVE_DIGITAL
FROM TEMP_SUB_PROFILE_MTH_ACTIVE_CALLER PRO
INNER JOIN TEMP_SUB_FLAG_SEGMENT_EXTENDED_AOU DIGI
	ON PRO.MNTH_ID = DIGI.MNTH_ID
	AND PRO.PROD_KEY = DIGI.PROD_KEY
WHERE Digi.TOTAL_DIGIT = 1
)
SEGMENTED BY HASH(MNTH_ID, PROD_KEY) ALL NODES
;

-- MERGE ACTIVE REVENUE PROFILE WITH DIGITAL AND CHURN CUSTOMER
DROP TABLE IF EXISTS TEMP_SUB_MERGE_FLAG_SURVIVAL;

CREATE LOCAL TEMP TABLE TEMP_SUB_MERGE_FLAG_SURVIVAL ON COMMIT PRESERVE ROWS AS
(
SELECT
      MNTH_ID
	, PROD_KEY
	, MAX(ACTIVE)                           AS ACTIVE          
	, SUM(COALESCE(REVN_AMNT,0))            AS REVN_AMNT     
	, MAX(ACTIVE_DIGITAL)                   AS ACTIVE_DIGITAL  
	, MAX(ACTIVE_CHURN)                     AS ACTIVE_CHURN  
	, MAX(ACTIVE_CALLER)                    AS ACTIVE_CALLER
FROM (
  -- Active + Revenue rows
  SELECT
      R.MNTH_ID
    , R.PROD_KEY
    , 1 AS ACTIVE
    , R.REVN_AMNT::DECIMAL(18,6)
    , 0 AS ACTIVE_DIGITAL
    , 0 AS ACTIVE_CHURN
	, R.ACTIVE_CALLER
	
  FROM TEMP_SUB_PROFILE_REV R
  UNION ALL
  -- Digital-only rows
  SELECT
      D.MNTH_ID
    , D.PROD_KEY
    , 0 AS ACTIVE
    , CAST(NULL AS DECIMAL(18,6)) AS REVN_AMNT
    , 1 AS ACTIVE_DIGITAL
    , 0 AS ACTIVE_CHURN
	, 0 AS ACTIVE_CALLER
  FROM TEMP_SUB_PROFILE_ACTIVE_DIGITAL D
) u
GROUP BY 
	  MNTH_ID
	, PROD_KEY
)
SEGMENTED BY HASH(MNTH_ID, PROD_KEY) ALL NODES
;

/* ============================================================
   10. LOAD GUARD - CHECK BEFORE WRITING THE MONTH
   ============================================================ */ 
-- LOAD_OK = 1 only if the month's profile is loaded (by 01) and the survival input covers it
-- LOAD_OK = 0 -> step 11 deletes, inserts and updates nothing; the survival table is left as it was
DROP TABLE IF EXISTS TEMP_LOAD_GUARD_SURV;

CREATE LOCAL TEMP TABLE TEMP_LOAD_GUARD_SURV ON COMMIT PRESERVE ROWS AS
(
SELECT
	  D.MNTH_ID
	, P.NSUBR_PROFILE
	, S.NSUBR_SURV
	, CASE
		WHEN P.NSUBR_PROFILE = 0                     THEN 0  -- profile for the month not loaded
		WHEN S.NSUBR_SURV < P.NSUBR_PROFILE * 0.9    THEN 0  -- survival input incomplete
		ELSE 1
	  END AS LOAD_OK
FROM TEMP_DATE D
CROSS JOIN (
	SELECT COUNT(DISTINCT PROD_KEY) AS NSUBR_PROFILE
	FROM SANDBOX.AUTO_SUB_PROFILE_MTH
	WHERE MNTH_ID IN (SELECT MNTH_ID FROM TEMP_DATE)
) P
CROSS JOIN (SELECT COUNT(DISTINCT PROD_KEY) AS NSUBR_SURV FROM TEMP_SUB_MERGE_FLAG_SURVIVAL) S
)
SEGMENTED BY HASH(MNTH_ID) ALL NODES
;

