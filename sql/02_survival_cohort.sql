(
    SELECT
          CAST(TO_CHAR(ADD_MONTHS(TO_DATE(CAST(MNTH_ID AS VARCHAR(6)), 'YYYYMM'), -10), 'YYYYMM') AS INT)
    FROM TEMP_DATE
