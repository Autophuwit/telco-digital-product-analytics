(
    SELECT
          MAX(MNTH_ID) AS RPT_MNTH_ID
    FROM TEMP_DATE
)
, FLG(FCD, FLABEL) AS
(
      SELECT 'OTT',    'MAPP_OTT_FLAG'    UNION ALL
      SELECT 'GAME',   'MAPP_GAME_FLAG'   UNION ALL
      SELECT 'UP2U',   'MAPP_UP2U_FLAG'   UNION ALL
      SELECT 'SECURE', 'MAPP_SECURE_FLAG' UNION ALL
      SELECT 'DCB',    'MAPP_DCB_FLAG'    UNION ALL
      SELECT 'CPA',    'MAPP_CPA_FLAG'
)
SELECT
      A.ENTITY
    , '02' AS REPORT_ORDER
    , CASE FLG.FCD
          WHEN 'OTT'    THEN A.MAPP_OTT_FLAG
          WHEN 'GAME'   THEN A.MAPP_GAME_FLAG
          WHEN 'UP2U'   THEN A.MAPP_UP2U_FLAG
          WHEN 'SECURE' THEN A.MAPP_SECURE_FLAG
          WHEN 'DCB'    THEN A.MAPP_DCB_FLAG
          WHEN 'CPA'    THEN A.MAPP_CPA_FLAG
      END AS REPORT_LEVEL
    , A.ACCT_TYPE
    , CAST('All Parameter' AS VARCHAR(200)) AS PARAMETER_INDEX

    , SUM(A.NSUBR) / COUNT(DISTINCT A.MNTH_ID) AS NSUBRX

    /* =====================
       NUMERATOR (ACTIVE_CALLER_Mxx)
       ===================== */
    , (SUM(CASE WHEN A.MNTH_ID <= R.RPT_MNTH_ID THEN A.ACTIVE_CALLER_M01 ELSE 0 END) * 1.00) AS ACTIVE_CALLER_M01
