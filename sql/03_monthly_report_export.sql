-- MERGE DIGITAL PRODUCT
DROP TABLE IF EXISTS TEMP_SUB_MERGE_DIGITAL;

CREATE LOCAL TEMP TABLE TEMP_SUB_MERGE_DIGITAL ON COMMIT PRESERVE ROWS AS 
(
WITH TEMP_EXPORT AS 
(
	SELECT 'BRAND_A' AS ENTITY
	, A.MNTH_ID
	, CASE WHEN A.PROD_CTGRY = 'Postpay' THEN 'Postpaid' ELSE 'Prepaid' END AS ACCT_TYPE
	, CASE WHEN A.SIM_TYPE = 'I' THEN 'Individual' ELSE A.SIM_TYPE END AS SUBR_TYPE
	
	, A.PROD_KEY AS SUBR_ID
	
	, CASE WHEN TOTAL_DIGIT = 1 THEN 'Digital User' ELSE 'Non-Digital User' END AS DIGITAL_USER_FLAG
	, CASE WHEN TOTAL_DIGIT_PROD = 0 THEN 'Non-Digital User' ELSE TOTAL_DIGIT_PROD || ' Product' END AS NO_OF_DIGITAL_PRODUCT
	
	, CASE WHEN OTT_FLAG = 1    THEN 'OTT'    ELSE '' END AS MAPP_OTT_FLAG
	, CASE WHEN GAME_FLAG = 1   THEN 'GAME'   ELSE '' END AS MAPP_GAME_FLAG
	, CASE WHEN UP2U_FLAG = 1   THEN 'UP2U'   ELSE '' END AS MAPP_UP2U_FLAG
	, CASE WHEN SECURE_FLAG = 1 THEN 'SECURE' ELSE '' END AS MAPP_SECURE_FLAG
	, CASE WHEN DCB_FLAG = 1    THEN 'DCB'    ELSE '' END AS MAPP_DCB_FLAG
	, CASE WHEN CPA_FLAG = 1    THEN 'CPA'    ELSE '' END AS MAPP_CPA_FLAG
	
	, CASE
		WHEN A.AOU <= 365*1 THEN 'A) 0-1Y'
		WHEN A.AOU <= 365*2 THEN 'B) 1-2Y'
		WHEN A.AOU <= 365*3 THEN 'C) 2-3Y'
		WHEN A.AOU <= 365*4 THEN 'D) 3-4Y'
		WHEN A.AOU <= 365*5 THEN 'E) 4-5Y'
		ELSE 'F) >5Y'
	END AS AOU_BAND
	
	FROM SANDBOX.AUTO_LIFESTYLE_SUB_FLAG_SEGMENT AS A
	
	WHERE A.MNTH_ID IN (SELECT MNTH_ID FROM TEMP_DATE)
)
SELECT A.*
	, MAPP_OTT_FLAG || '+' || MAPP_GAME_FLAG || '+' || MAPP_UP2U_FLAG || '+' || MAPP_SECURE_FLAG || '+' || MAPP_DCB_FLAG || '+' || MAPP_CPA_FLAG AS MIX_PRODUCT

FROM TEMP_EXPORT AS A

) 
SEGMENTED BY HASH(MNTH_ID, SUBR_ID) ALL NODES
;

UPDATE TEMP_SUB_MERGE_DIGITAL
SET MIX_PRODUCT = REGEXP_REPLACE(MIX_PRODUCT, '^\++', '')
;

UPDATE TEMP_SUB_MERGE_DIGITAL
SET MIX_PRODUCT = REGEXP_REPLACE(MIX_PRODUCT, '\++', '+')
;

SELECT A.ENTITY
	, A.MNTH_ID
	, A.ACCT_TYPE
	, A.SUBR_TYPE
	
	, A.DIGITAL_USER_FLAG
	, A.NO_OF_DIGITAL_PRODUCT
	, A.MIX_PRODUCT
	
	, SUM(1) AS ACTIVE_CITRINE_NSUBR
	, SUM(CASE WHEN A.DIGITAL_USER_FLAG = 'Digital User' THEN 1 ELSE 0 END) AS DIGITAL_NSUBR
	
	, SUM(B.REVN_AMNT) AS TOTAL_REVN_AMNT

FROM TEMP_SUB_MERGE_DIGITAL AS A
LEFT OUTER JOIN (SELECT * FROM SANDBOX.AUTO_LIFESTYLE_SUB_AGG_REVENUE_MTH WHERE MNTH_ID IN (SELECT MNTH_ID FROM TEMP_DATE)) AS B
	ON A.SUBR_ID = B.PROD_KEY
	AND A.MNTH_ID = B.MNTH_ID

GROUP BY 1, 2, 3, 4, 5, 6, 7
ORDER BY 1, 2, 3, 4, 5, 6, 7
;

