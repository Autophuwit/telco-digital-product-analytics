DROP TABLE IF EXISTS TEMP_EXPORT_SURVIVAL;

CREATE LOCAL TEMP TABLE TEMP_EXPORT_SURVIVAL ON COMMIT PRESERVE ROWS AS
(
WITH RPT AS
(
    SELECT
          MAX(MNTH_ID) AS RPT_MNTH_ID
    FROM TEMP_DATE
)
SELECT
      A.ENTITY
    , '01' AS REPORT_ORDER
    , CASE WHEN A.DIGITAL_USER_FLAG = 1 THEN 'Digital' ELSE 'Non-Digital' END AS REPORT_LEVEL
    , A.ACCT_TYPE
    , CAST('All Parameter' AS VARCHAR(200)) AS PARAMETER_INDEX

    , SUM(A.NSUBR) / COUNT(DISTINCT A.MNTH_ID) AS NSUBRX

    /* =====================
       NUMERATOR (ACTIVE_CALLER_Mxx)
       ===================== */
    , (SUM(CASE WHEN A.MNTH_ID <= R.RPT_MNTH_ID THEN A.ACTIVE_CALLER_M01 ELSE 0 END) * 1.00) AS ACTIVE_CALLER_M01
    , (SUM(CASE WHEN A.MNTH_ID <= CAST(TO_CHAR(ADD_MONTHS(TO_DATE(CAST(R.RPT_MNTH_ID AS VARCHAR(6)), 'YYYYMM'), -1), 'YYYYMM') AS INT) THEN A.ACTIVE_CALLER_M02 ELSE 0 END) * 1.00) AS ACTIVE_CALLER_M02
    , (SUM(CASE WHEN A.MNTH_ID <= CAST(TO_CHAR(ADD_MONTHS(TO_DATE(CAST(R.RPT_MNTH_ID AS VARCHAR(6)), 'YYYYMM'), -2), 'YYYYMM') AS INT) THEN A.ACTIVE_CALLER_M03 ELSE 0 END) * 1.00) AS ACTIVE_CALLER_M03
    , (SUM(CASE WHEN A.MNTH_ID <= CAST(TO_CHAR(ADD_MONTHS(TO_DATE(CAST(R.RPT_MNTH_ID AS VARCHAR(6)), 'YYYYMM'), -3), 'YYYYMM') AS INT) THEN A.ACTIVE_CALLER_M04 ELSE 0 END) * 1.00) AS ACTIVE_CALLER_M04
    , (SUM(CASE WHEN A.MNTH_ID <= CAST(TO_CHAR(ADD_MONTHS(TO_DATE(CAST(R.RPT_MNTH_ID AS VARCHAR(6)), 'YYYYMM'), -4), 'YYYYMM') AS INT) THEN A.ACTIVE_CALLER_M05 ELSE 0 END) * 1.00) AS ACTIVE_CALLER_M05
    , (SUM(CASE WHEN A.MNTH_ID <= CAST(TO_CHAR(ADD_MONTHS(TO_DATE(CAST(R.RPT_MNTH_ID AS VARCHAR(6)), 'YYYYMM'), -5), 'YYYYMM') AS INT) THEN A.ACTIVE_CALLER_M06 ELSE 0 END) * 1.00) AS ACTIVE_CALLER_M06
    , (SUM(CASE WHEN A.MNTH_ID <= CAST(TO_CHAR(ADD_MONTHS(TO_DATE(CAST(R.RPT_MNTH_ID AS VARCHAR(6)), 'YYYYMM'), -6), 'YYYYMM') AS INT) THEN A.ACTIVE_CALLER_M07 ELSE 0 END) * 1.00) AS ACTIVE_CALLER_M07
    , (SUM(CASE WHEN A.MNTH_ID <= CAST(TO_CHAR(ADD_MONTHS(TO_DATE(CAST(R.RPT_MNTH_ID AS VARCHAR(6)), 'YYYYMM'), -7), 'YYYYMM') AS INT) THEN A.ACTIVE_CALLER_M08 ELSE 0 END) * 1.00) AS ACTIVE_CALLER_M08
    , (SUM(CASE WHEN A.MNTH_ID <= CAST(TO_CHAR(ADD_MONTHS(TO_DATE(CAST(R.RPT_MNTH_ID AS VARCHAR(6)), 'YYYYMM'), -8), 'YYYYMM') AS INT) THEN A.ACTIVE_CALLER_M09 ELSE 0 END) * 1.00) AS ACTIVE_CALLER_M09
    , (SUM(CASE WHEN A.MNTH_ID <= CAST(TO_CHAR(ADD_MONTHS(TO_DATE(CAST(R.RPT_MNTH_ID AS VARCHAR(6)), 'YYYYMM'), -9), 'YYYYMM') AS INT) THEN A.ACTIVE_CALLER_M10 ELSE 0 END) * 1.00) AS ACTIVE_CALLER_M10
    , (SUM(CASE WHEN A.MNTH_ID <= CAST(TO_CHAR(ADD_MONTHS(TO_DATE(CAST(R.RPT_MNTH_ID AS VARCHAR(6)), 'YYYYMM'), -10), 'YYYYMM') AS INT) THEN A.ACTIVE_CALLER_M11 ELSE 0 END) * 1.00) AS ACTIVE_CALLER_M11
    , (SUM(CASE WHEN A.MNTH_ID <= CAST(TO_CHAR(ADD_MONTHS(TO_DATE(CAST(R.RPT_MNTH_ID AS VARCHAR(6)), 'YYYYMM'), -11), 'YYYYMM') AS INT) THEN A.ACTIVE_CALLER_M12 ELSE 0 END) * 1.00) AS ACTIVE_CALLER_M12

    /* =====================
       DENOMINATOR (ALL_Mxx)  = base cohort count (ACTIVE_CALLER_M01)
       ===================== */
    , DECODE(NVL(SUM(CASE WHEN A.MNTH_ID <= R.RPT_MNTH_ID THEN A.ACTIVE_CALLER_M01 END), 0), 0, 1
            , SUM(CASE WHEN A.MNTH_ID <= R.RPT_MNTH_ID THEN A.ACTIVE_CALLER_M01 END)) AS ALL_M01

    , DECODE(NVL(SUM(CASE WHEN A.MNTH_ID <= CAST(TO_CHAR(ADD_MONTHS(TO_DATE(CAST(R.RPT_MNTH_ID AS VARCHAR(6)), 'YYYYMM'), -1), 'YYYYMM') AS INT) THEN A.ACTIVE_CALLER_M01 END), 0), 0, 1
