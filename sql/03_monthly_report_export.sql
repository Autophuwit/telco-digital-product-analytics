DROP TABLE IF EXISTS TEMP_ARPU_UPLIFT;

CREATE LOCAL TEMP TABLE TEMP_ARPU_UPLIFT ON COMMIT PRESERVE ROWS AS 
(
SELECT 
	  CURR.MNTH_ID AS MNTH_ID
	, PREV.MNTH_ID AS PREV_MNTH_ID
	
	, CURR.PROD_KEY
	, CURR.PROD_CTGRY
	, 'BRAND_A' AS ENTITY
	, PREV.TOTAL_DIGIT_PROD || '-' || CURR.TOTAL_DIGIT_PROD AS MOVEMENT_FLAG
	, CASE 
		WHEN CURR.TOTAL_DIGIT_PROD > PREV.TOTAL_DIGIT_PROD THEN 'Move Up'
		WHEN CURR.TOTAL_DIGIT_PROD < PREV.TOTAL_DIGIT_PROD THEN 'Move Down'
		ELSE 'Move Maintain'
	END AS MOVEMENT_TYPE
	, 'Add ' || CURR.TOTAL_DIGIT_PROD - PREV.TOTAL_DIGIT_PROD || ' Product' AS ADD_PRODUCT_FLAG 
  
FROM (SELECT * FROM sandbox.AUTO_LIFESTYLE_SUB_FLAG_SEGMENT WHERE MNTH_ID IN (SELECT MNTH_ID FROM TEMP_DATE)) CURR
INNER JOIN sandbox.AUTO_LIFESTYLE_SUB_FLAG_SEGMENT  PREV
	ON PREV.MNTH_ID = CAST(TO_CHAR(ADD_MONTHS( TO_DATE(CAST(CURR.MNTH_ID AS VARCHAR(6)) || '01','YYYYMMDD'), -1 ),'YYYYMM') AS INT)
	AND CURR.PROD_KEY = PREV.PROD_KEY
)
SEGMENTED BY HASH(MNTH_ID, PROD_KEY) ALL NODES
;


SELECT 
	  A.ENTITY
	, A.MNTH_ID
	, A.PROD_CTGRY
	
	, A.MOVEMENT_TYPE
	, A.ADD_PRODUCT_FLAG
	, A.MOVEMENT_FLAG
	
	
	, SUM(1) AS NSUBR
	
	, SUM(R2.REVN_AMNT) AS REVENUE_BEFORE
	, SUM(R1.REVN_AMNT) AS REVENUE_AFTER

FROM TEMP_ARPU_UPLIFT A
LEFT JOIN (SELECT * FROM SANDBOX.AUTO_LIFESTYLE_SUB_AGG_REVENUE_MTH WHERE MNTH_ID IN (SELECT MNTH_ID FROM TEMP_DATE))  R1
	ON A.MNTH_ID = R1.MNTH_ID
	AND A.PROD_KEY = R1.PROD_KEY
LEFT JOIN (SELECT * FROM SANDBOX.AUTO_LIFESTYLE_SUB_AGG_REVENUE_MTH WHERE MNTH_ID IN (SELECT CAST(TO_CHAR(ADD_MONTHS( TO_DATE(CAST(MNTH_ID AS VARCHAR(6)) || '01','YYYYMMDD'), -1 ),'YYYYMM') AS INT) FROM TEMP_DATE)) R2
	ON A.PREV_MNTH_ID = R2.MNTH_ID
	AND A.PROD_KEY = R2.PROD_KEY
GROUP BY 1, 2, 3, 4, 5, 6
ORDER BY 1, 2, 3, 4, 5, 6
;
   
