/* ============================================================
   1. RUN DATE (FROM THE PARAMETER)
   ============================================================ */
DROP TABLE IF EXISTS TEMP_DATE;

CREATE LOCAL TEMP TABLE TEMP_DATE ON COMMIT PRESERVE ROWS AS
(
SELECT
	  GREG_MTH_ID AS MNTH_ID
	, MAX(GREG_DT_DT) AS MAX_RUN_DATE
	, CAST(TO_CHAR(ADD_MONTHS(TO_DATE(CAST(GREG_MTH_ID AS VARCHAR(6)), 'YYYYMM'), -11), 'YYYYMM') AS INT) AS FIRST_COHORT_MNTH_ID
	, CAST(TO_CHAR(ADD_MONTHS(TO_DATE(CAST(GREG_MTH_ID AS VARCHAR(6)), 'YYYYMM'),  -1), 'YYYYMM') AS INT) AS PREV_MNTH_ID
FROM EDW.DTN_GEOG_CLDR
WHERE GREG_MTH_ID = :RUN_MNTH
GROUP BY 1
)
SEGMENTED BY HASH(MNTH_ID) ALL NODES
;


/* ============================================================
   2. STATUS OF EVERY SUBSCRIBER IN THE RUN MONTH
   ============================================================ */
-- ACTIVE CALLER AT MONTH END
DROP TABLE IF EXISTS TEMP_SUB_DIM_PROD_KPI;

CREATE LOCAL TEMP TABLE TEMP_SUB_DIM_PROD_KPI ON COMMIT PRESERVE ROWS AS
(
SELECT DISTINCT
	  PROD_KEY
FROM EDW.DIM_PROD_KPI
WHERE VC_PAR_KEY IN (SELECT MAX_RUN_DATE FROM TEMP_DATE)
AND ACTV_CALLER_IND = 1
)
SEGMENTED BY HASH(PROD_KEY) ALL NODES
;

-- ACTIVE / REVENUE / DIGITAL / CALLER FOR THE RUN MONTH (FROM THE TABLES WRITTEN BY 01)
DROP TABLE IF EXISTS TEMP_SUB_STATUS_MTH;

CREATE LOCAL TEMP TABLE TEMP_SUB_STATUS_MTH ON COMMIT PRESERVE ROWS AS
(
SELECT
	  PRO.PROD_KEY
	, 1                                                       AS ACTIVE
	, COALESCE(MAX(REV.REVN_AMNT), 0)                         AS REVN_AMNT
	, MAX(CASE WHEN DIGI.TOTAL_DIGIT = 1 THEN 1 ELSE 0 END)   AS ACTIVE_DIGITAL
	, 0                                                       AS ACTIVE_CHURN
	, MAX(CASE WHEN KPI.PROD_KEY IS NOT NULL THEN 1 ELSE 0 END) AS ACTIVE_CALLER
FROM SANDBOX.AUTO_SUB_PROFILE_MTH PRO
LEFT JOIN SANDBOX.AUTO_LIFESTYLE_SUB_AGG_REVENUE_MTH REV
	ON PRO.MNTH_ID = REV.MNTH_ID
	AND PRO.PROD_KEY = REV.PROD_KEY
LEFT JOIN SANDBOX.AUTO_LIFESTYLE_SUB_FLAG_SEGMENT DIGI
	ON PRO.MNTH_ID = DIGI.MNTH_ID
	AND PRO.PROD_KEY = DIGI.PROD_KEY
LEFT JOIN TEMP_SUB_DIM_PROD_KPI KPI
	ON PRO.PROD_KEY = KPI.PROD_KEY
WHERE PRO.MNTH_ID IN (SELECT MNTH_ID FROM TEMP_DATE)
GROUP BY
	  PRO.PROD_KEY
)
SEGMENTED BY HASH(PROD_KEY) ALL NODES
;


/* ============================================================
   3. LOAD GUARD
   ============================================================ */
-- LOAD_OK = 1 only if the run month's profile is loaded and not much smaller than last month
DROP TABLE IF EXISTS TEMP_LOAD_GUARD_SURV;

CREATE LOCAL TEMP TABLE TEMP_LOAD_GUARD_SURV ON COMMIT PRESERVE ROWS AS
(
SELECT
	  D.MNTH_ID
	, N.NSUBR_NEW
	, P.NSUBR_PREV
	, CASE
		WHEN N.NSUBR_NEW = 0                                       THEN 0  -- run month not loaded by 01
		WHEN P.NSUBR_PREV > 0 AND N.NSUBR_NEW < P.NSUBR_PREV * 0.9 THEN 0  -- dropped > 10% vs last month
		ELSE 1
	  END AS LOAD_OK
FROM TEMP_DATE D
CROSS JOIN (SELECT COUNT(*) AS NSUBR_NEW FROM TEMP_SUB_STATUS_MTH) N
CROSS JOIN (
	SELECT COUNT(*) AS NSUBR_PREV
	FROM SANDBOX.AUTO_LIFESTYLE_SUB_SURVIVAL_LONG
	WHERE COHORT_MNTH_ID IN (SELECT PREV_MNTH_ID FROM TEMP_DATE)
	AND MONTH_NO = 1
) P
)
SEGMENTED BY HASH(MNTH_ID) ALL NODES
;

-- CHECK: LOAD_OK MUST BE 1 BEFORE CONTINUING
SELECT * FROM TEMP_LOAD_GUARD_SURV;


/* ============================================================
   4. WRITE THE RUN MONTH FOR THE LAST 12 COHORTS (RE-RUN SAFE)
   ============================================================ */
-- replaces rows measured in the run month only when LOAD_OK = 1 (one transaction, autocommit off)
DELETE FROM SANDBOX.AUTO_LIFESTYLE_SUB_SURVIVAL_LONG
WHERE ACTIVITY_MNTH_ID IN (SELECT MNTH_ID FROM TEMP_LOAD_GUARD_SURV WHERE LOAD_OK = 1);

-- one row per (cohort member, month number):
--   cohort  = subscribers in the profile of each of the last 12 months (incl. the run month -> MONTH_NO 1)
--   status  = their status in the run month; not found -> 0 (same as the 0-initialised wide table)
INSERT /*+ DIRECT */ INTO SANDBOX.AUTO_LIFESTYLE_SUB_SURVIVAL_LONG
SELECT
	  A.MNTH_ID                                                                   AS COHORT_MNTH_ID
	, A.PROD_KEY
	, DATEDIFF('month', TO_DATE(CAST(A.MNTH_ID AS VARCHAR(6)), 'YYYYMM')
	                  , TO_DATE(CAST(D.MNTH_ID AS VARCHAR(6)), 'YYYYMM')) + 1    AS MONTH_NO
	, D.MNTH_ID                                                                   AS ACTIVITY_MNTH_ID
	, COALESCE(S.ACTIVE, 0)                                                       AS ACTIVE
	, COALESCE(S.REVN_AMNT, 0)                                                    AS REVN_AMNT
	, COALESCE(S.ACTIVE_DIGITAL, 0)                                               AS ACTIVE_DIGITAL
	, COALESCE(S.ACTIVE_CHURN, 0)                                                 AS ACTIVE_CHURN
	, COALESCE(S.ACTIVE_CALLER, 0)                                                AS ACTIVE_CALLER
FROM (
	SELECT DISTINCT
		  MNTH_ID
		, PROD_KEY
	FROM SANDBOX.AUTO_SUB_PROFILE_MTH
	WHERE MNTH_ID BETWEEN (SELECT FIRST_COHORT_MNTH_ID FROM TEMP_DATE) AND (SELECT MNTH_ID FROM TEMP_DATE)
) A
CROSS JOIN TEMP_DATE D
LEFT JOIN TEMP_SUB_STATUS_MTH S
	ON A.PROD_KEY = S.PROD_KEY
WHERE EXISTS (SELECT 1 FROM TEMP_LOAD_GUARD_SURV WHERE LOAD_OK = 1)
;

COMMIT;

-- CHECK: ONE ROW PER COHORT MEMBER PER MONTH NUMBER (EXPECT 0 ROWS)
SELECT COHORT_MNTH_ID, PROD_KEY, MONTH_NO, COUNT(*) AS N
FROM SANDBOX.AUTO_LIFESTYLE_SUB_SURVIVAL_LONG
WHERE ACTIVITY_MNTH_ID IN (SELECT MNTH_ID FROM TEMP_DATE)
GROUP BY 1, 2, 3
HAVING COUNT(*) > 1
;
