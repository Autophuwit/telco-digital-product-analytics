/* ============================================================
   02 v2 - ROLLING 12-MONTH SURVIVAL (LONG FORMAT)
   ------------------------------------------------------------
   Same result as 02_survival_cohort.sql, rewritten to be easier to run and maintain:
     - the run month is a parameter, set once        -> no "CHANGE MNTH_ID HERE" edits
     - one INSERT per run (one row per cohort member x month number)
       instead of 1 INSERT + 11 UPDATE blocks         -> adding M13..M24 needs no new code
     - reads the permanent tables written by 01      -> no dependency on 01's temp tables / session
     - re-run safe: the run month is replaced, guarded against an empty source
     - view _V pivots back to the wide M01..M12 layout, so 03_monthly_report_export.sql only
       needs the table name changed

   Run (vsql):   vsql -v RUN_MNTH=202511 -v ON_ERROR_STOP=on -f 02_survival_cohort_v2.sql
   Backfill:     run once per month, oldest first
   ============================================================ */


/* ============================================================
   0. ONE-OFF: TABLE + WIDE VIEW (SAFE TO RE-RUN)
   ============================================================ */
CREATE TABLE IF NOT EXISTS SANDBOX.AUTO_LIFESTYLE_SUB_SURVIVAL_LONG
(
      COHORT_MNTH_ID    INT            -- month the subscriber entered the cohort (= MNTH_ID of the wide table)
    , PROD_KEY          INT
    , MONTH_NO          INT            -- 1 = cohort month, 2 = next month ... 12
    , ACTIVITY_MNTH_ID  INT            -- month the status below was measured
    , ACTIVE            INT
    , REVN_AMNT         NUMERIC(18,6)
    , ACTIVE_DIGITAL    INT
    , ACTIVE_CHURN      INT
    , ACTIVE_CALLER     INT
)
ORDER BY COHORT_MNTH_ID, PROD_KEY
SEGMENTED BY HASH(PROD_KEY) ALL NODES
PARTITION BY ACTIVITY_MNTH_ID
;

